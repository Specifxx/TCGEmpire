// ─────────────────────────────────────────────────────────────────────────────
// The trust and policy pages (/about, /editorial-policy, /methodology,
// /privacy, /terms, /contact, /support) describe the site to the people most
// likely to check it: a reviewer after a "low value content" rejection, and a
// buyer deciding whether to trust a number. Rewritten 2026-09-26 ("Blog and
// tools, joined up" in DECISIONS.md) because several of their claims no longer
// matched the code — a password sign-in, a removed marketplace, "the whole
// catalogue" searched on eBay daily, history "per market per day".
//
// These tests pin every figure the pages TYPE to the constant that produces it,
// so a change to the importer, a threshold or a cookie fails here rather than
// leaving the policy quietly wrong. Numbers the pages COMPUTE (store counts
// from RETAILER_LIST, the FX table from USD_TO, the probe's addresses from the
// postage snapshot) are asserted to stay computed.
// ─────────────────────────────────────────────────────────────────────────────

const ROOT = process.cwd();
const read = (p: string) => readFileSync(join(ROOT, p), "utf8");
// Comments explain what USED to be claimed; strip them so a removed claim named
// in a note does not read as copy. Line comments first (a "/card/*"-shaped
// string in a // note would otherwise open a block comment), keeping URLs.
const code = (p: string) => read(p).replace(/(^|[^:])\/\/.*$/gm, "$1").replace(/\/\*[\s\S]*?\*\//g, "");
// JSX wraps sentences across lines; collapse whitespace so a sentence matches whole.
const text = (p: string) => code(p).replace(/\s+/g, " ");

const ABOUT = "src/app/about/page.tsx";
const POLICY = "src/app/editorial-policy/page.tsx";
const METHOD = "src/app/methodology/page.tsx";
const PRIVACY = "src/app/privacy/page.tsx";
const TERMS = "src/app/terms/page.tsx";
const CONTACT = "src/app/contact/page.tsx";
const SUPPORT = "src/app/support/page.tsx";
const TRUST_PAGES = [ABOUT, POLICY, METHOD, PRIVACY, TERMS, CONTACT, SUPPORT];

/** The right-hand side of `name = …` in a source file, trimmed. */
function constant(file: string, name: string): string {
  const m = new RegExp(`\\b${name}\\s*(?::[^=]+)?=\\s*([^;\\n]+)`).exec(read(file));
  assert.ok(m, `${file} no longer defines ${name} — re-derive what the trust pages say about it`);
  return m[1].trim();
}
const num = (file: string, name: string) => Number(constant(file, name).replace(/_/g, ""));

