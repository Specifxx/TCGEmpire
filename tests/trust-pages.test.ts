test("the refresh list matches the importer's real cadence", () => {
  const policy = text(POLICY);
  const workflow = read(".github/workflows/refresh-prices.yml");
  assert.match(workflow, /cron: "0 7 \* \* \*"/);
  assert.match(workflow, /cron: "0 19 \* \* \*"/);
  assert.match(policy, /twice a day, at 07:00 and 19:00 UTC/);

  const importer = read("src/lib/price-import.ts");
  const floor = /EBAY_MIN_VALUE_CENTS \?\? (\d+)/.exec(importer);
  assert.ok(floor, "EBAY_MIN_VALUE_USD_CENTS's default moved");
  assert.equal(Number(floor[1]), 500, "the policy says US$5 — update it with the floor");
  assert.match(policy, /worth at least US\$5 at TCGplayer&rsquo;s US market price/);
  assert.match(importer, /EBAY_SKIP_RARITIES = new Set\(\["Common", "Uncommon"\]\)/);
  assert.match(policy, /commons and uncommons are skipped/);

  const markets = (name: string) =>
    [...new RegExp(`${name}: EbayMarketCfg\\[\\] = \\[([\\s\\S]*?)\\];`).exec(importer)![1].matchAll(/country: "(\w+)"/g)].map((m) => m[1]);
  assert.deepEqual(markets("EBAY_ALWAYS_MARKETS"), ["AU", "US"]);
  assert.deepEqual(markets("EBAY_ROTATING_MARKETS"), ["UK", "SG", "EU"]);
  assert.match(policy, /Australia and the US are searched every day; the UK, Singapore and the EU take turns, one a day/);
  assert.match(importer, /refreshEbayChasePrintings\(ebayMarketsForDay\(ebayDayIndex\(\)\)\)/);
  assert.match(policy, /promo, Signature and overnumbered printings in that day&rsquo;s markets are searched again/);
  assert.match(importer, /retailerName: "eBay US",[\s\S]{0,80}USD_TO\.CAD/);
  assert.match(policy, /Canada&rsquo;s eBay rows are the US results converted to Canadian dollars/);

  // Daily since 2026-10-03 (weekly 2026-08-31 → 10-03): every import writes or
  // replaces the day's file (lib/price-history-store.ts) with no interval gate.
  assert.doesNotMatch(read("src/lib/price-history.ts"), /HISTORY_MIN_INTERVAL_DAYS =/, "an interval gate came back — re-derive what the policy says");
  assert.match(read("src/lib/price-import.ts"), /writeCardHistoryDay\(day, points\)/);
  assert.match(policy, /every day we record each card&rsquo;s cheapest price across the Australian, US, UK and Singapore markets, in US dollars/);
  assert.match(read("src/lib/price-history.ts"), /GLOBAL_LOW_MARKETS: readonly Country\[\] = \["AU", "US", "UK", "SG"\]/);

  assert.match(policy, /STORE_ROWS_MAX_AGE_H \/ 24/, "the stale-row window is computed from STORE_ROWS_MAX_AGE_H");
  assert.doesNotMatch(policy, /whole catalogue is searched once|one recorded point per card per market per day|Index and homepage: hourly/i);
});

